def multimodal_add_model(
    data_meta, maxlen, im_size, n_class=2,
    bert_backbone: TFBertModel | None = None,
    bert_trainable: bool = False,
    vgg_trainable: bool = False
):

    # ----- Inputs -----
    inp_meta = Input(shape=(data_meta.shape[1], 1), name="meta")
    inp_t1   = Input(shape=(maxlen,), dtype=tf.int32, name="text1_ids")
    inp_t2   = Input(shape=(maxlen,), dtype=tf.int32, name="text2_ids")
    inp_img  = Input(shape=im_size, name="image")

    # ----- BERT backbone (shared) -----
    if bert_backbone is None:
        bert_backbone = _load_bert_backbone()
    bert_layer = BertLayer(bert_backbone, trainable=bert_trainable, name="bert_encoder")

    t1_feat = bert_layer(inp_t1)                 # (batch, hidden)
    t1_feat = Dense(128, activation="relu", name="t1_fc")(t1_feat)

    t2_feat = bert_layer(inp_t2)                 # (batch, hidden)
    t2_feat = Dense(128, activation="relu", name="t2_fc")(t2_feat)

    # ----- Image encoder (VGG19) -----
    vgg = VGG19(include_top=False, weights="imagenet", input_shape=im_size, pooling=None)
    vgg.trainable = vgg_trainable
    img_feat = vgg(inp_img)                      # (batch, H', W', C')
    img_feat = GlobalAveragePooling2D(name="img_gap")(img_feat)
    img_feat = Dense(128, activation="relu", name="img_fc")(img_feat)

    # ----- Meta encoder -----
    meta_feat = Conv1D(32, kernel_size=2, activation="relu", name="meta_conv")(inp_meta)
    meta_feat = GlobalAveragePooling1D(name="meta_gap")(meta_feat)
    meta_feat = Dense(128, activation="relu", name="meta_fc")(meta_feat)

    # ----- Fusion -----
    fused = Add(name="add_fusion")([t1_feat, t2_feat, img_feat, meta_feat])
    x = Dense(128, activation="relu", name="fusion_fc")(fused)
    out = Dense(n_class, activation="softmax", name="final_softmax")(x)

    model = Model(
        inputs=[inp_meta, inp_t1, inp_t2, inp_img],
        outputs=out,
        name="MultiModalAddFusion"
    )
    return model


