def _load_bert_backbone(model_name="bert-base-uncased"):
    """
    Robust loader for TFBertModel that avoids the safetensors iteration error.
    Tries native TF weights first, then falls back to converting PyTorch weights
    with use_safetensors=False.
    """
    try:
        # Prefer native TF weights
        return TFBertModel.from_pretrained(model_name, from_pt=False)
    except Exception as e1:
        try:
            # Fallback: convert PT -> TF, but disable safetensors to avoid the 'safe_open' error
            return TFBertModel.from_pretrained(model_name, from_pt=True, use_safetensors=False)
        except Exception as e2:
            raise RuntimeError(
                f"Failed to load TFBertModel. TF error: {e1}\nFallback (PT->TF) error: {e2}"
            )


