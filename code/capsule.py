def build_multimodal_capsule_model(
    data_meta,
    maxlen,
    im_size,
    n_class=2,
    routing_iters=3
):
    # Inputs
    inp_meta = Input(shape=(data_meta.shape[1], 1), name="meta")
    inp_t1   = Input(shape=(maxlen,), dtype=tf.int32, name="text1")
    inp_t2   = Input(shape=(maxlen,), dtype=tf.int32, name="text2")
    inp_img  = Input(shape=im_size, name="image")

    # ----- Text Branch (Cosine Similarity between two texts) -----
   # e1 = BertLayer()(inp_t1)  # [batch, embed_dim]
   # e2 = BertLayer()(inp_t2)  # [batch, embed_dim]


    e1 = bert_layer_wrapped(inp_t1)
    e2 = bert_layer_wrapped(inp_t2)

    # Capsule encoding for each text separately
    pc_t1 = PrimaryCapDense(6, 8)(e1)
    dc_t1 = DigitCaps(1, 16, routings=routing_iters)(pc_t1)  # Single capsule

    pc_t2 = PrimaryCapDense(6, 8)(e2)
    dc_t2 = DigitCaps(1, 16, routings=routing_iters)(pc_t2)  # Single capsule

    # Flatten capsules for similarity
    caps_t1 = layers.Flatten()(dc_t1)  # [batch, 16]
    caps_t2 = layers.Flatten()(dc_t2)  # [batch, 16]

    # Custom Layer for safe cosine similarity
    class SafeCosineSimilarity(layers.Layer):
        def call(self, inputs):
            x1, x2 = inputs
            x1 = tf.where(tf.equal(tf.norm(x1, axis=-1, keepdims=True), 0.0), x1 + 1e-6, x1)
            x2 = tf.where(tf.equal(tf.norm(x2, axis=-1, keepdims=True), 0.0), x2 + 1e-6, x2)
            return tf.reduce_sum(tf.linalg.l2_normalize(x1, axis=-1) * tf.linalg.l2_normalize(x2, axis=-1), axis=-1, keepdims=True)

    # Cosine similarity explicitly
    txt_similarity = SafeCosineSimilarity(name="cosine_safe")([caps_t1, caps_t2])  # [batch, 1]
    txt_similarity_proj = layers.Dense(n_class, activation='elu', name="txt_sim_projection")(txt_similarity)


    # ----- Image Branch -----
    x_img = layers.Lambda(lambda z: preprocess_input(z))(inp_img)
    _vgg = VGG19(include_top=False, weights="imagenet")
    _vgg.trainable = False

    for layer in _vgg.layers:
      layer.trainable = ("block5" in layer.name)  # only fine-tune the top block

    v = _vgg(x_img)
    pc_img = PrimaryCapConv2D(32, 8, kernel_size=3, strides=2)(v)
    dc_img = DigitCaps(n_class, 16, routings=routing_iters)(pc_img)
    score_img = SquashNormMetric()(dc_img)            # [batch, n_class]

    # ----- Numeric (Meta) Branch -----
    nm = layers.Conv1D(32, 2, activation="relu")(inp_meta)
    nm = layers.Flatten()(nm)

    # Custom Layer for safe norm on numeric data
    class SafeNormNumeric(layers.Layer):
        def call(self, inputs):
            return tf.where(tf.equal(tf.norm(inputs, axis=-1, keepdims=True), 0.0), inputs + 1e-6, inputs)

    nm = SafeNormNumeric()(nm)
    pc_num = PrimaryCapDense(16, 8)(nm)
    dc_num = DigitCaps(n_class, 16, routings=routing_iters)(pc_num)
    score_num = SoftmaxNegEntropyPerClass()(dc_num)   # [batch, n_class]

    # ----- After Metrics Computation -----

    # Assume each metric outputs shape [batch, 2]
    # e.g., txt_similarity_proj, score_img, score_num all have [batch, 2]

    # Apply learnable weights W1, W2, W3 to each modality explicitly
    weighted_txt = layers.Dense(2, activation="linear", use_bias=False, name="W_txt")(txt_similarity_proj)
    weighted_img = layers.Dense(2, activation="linear", use_bias=False, name="W_img")(score_img)
    weighted_num = layers.Dense(2, activation="linear", use_bias=False, name="W_num")(score_num)

    # Concatenate weighted features explicitly
    concat_features = layers.Concatenate(axis=-1, name="concat_weighted_features")(
        [weighted_txt, weighted_img, weighted_num]  # shape: [batch, 6]
    )

    x = layers.BatchNormalization()(concat_features)
    x = layers.Dropout(0.15)(x)
    x = layers.Dense(128, activation="relu")(x)
    x = layers.Dropout(0.15)(x)
    out = layers.Dense(n_class, activation="tanh", name="final")(x)


    # Final Model
    return Model(
        inputs=[inp_meta, inp_t1, inp_t2, inp_img],
        outputs=out,
        name="MultiModalCapsule"
    )

