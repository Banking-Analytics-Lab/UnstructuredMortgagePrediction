class CosineSimMetric(layers.Layer):
    def __init__(self, n_class, dim_caps, **kwargs):
        super().__init__(**kwargs)
        self.n_class = n_class
        self.dim_caps = dim_caps

    def build(self, _):
        self.class_emb = self.add_weight(
            shape=(self.n_class, self.dim_caps),
            initializer="glorot_uniform",
            trainable=True
        )

    def call(self, caps_out):
        # caps_out: [batch, n_class, dim_caps]
        z_norm = tf.linalg.l2_normalize(caps_out, axis=-1)
        e_norm = tf.linalg.l2_normalize(self.class_emb, axis=-1)
        cos = tf.einsum("bcd,cd->bc", z_norm, e_norm)
        return (cos + 1.0) / 2.0  # [batch, n_class]

class SquashNormMetric(layers.Layer):
    def call(self, caps_out):
        return tf.norm(caps_out, axis=-1)  # [batch, n_class]

class SoftmaxNegEntropyPerClass(layers.Layer):
    def call(self, caps_out):
        # caps_out: [batch, n_class, dim_caps]
        # 1) capsule lengths → [batch, n_class]
        lengths = tf.norm(caps_out, axis=-1)
        # 2) softmax to get p → [batch, n_class]
        p = tf.nn.softmax(lengths, axis=-1)
        # 3) per-class neg‐entropy term: −p_i·log₂(p_i) → [batch, n_class]
        neg_ent = -p * tf.math.log(p + 1e-8) / tf.math.log(2.0)
        # 4) (optionally) shift by +1 if you want  in [1,1+…] rather than [0,…]
        scores = 1.0 + neg_ent
        return scores  # shape = [batch, n_class]

