# --------------------------------------------
# 1) squash non-linearity for capsules
# --------------------------------------------
def squash(vectors, axis=-1, epsilon=1e-7):
    s2 = tf.reduce_sum(tf.square(vectors), axis=axis, keepdims=True)
    scale = s2 / (1. + s2) / tf.sqrt(s2 + epsilon)
    return scale * vectors

